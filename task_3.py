world_champions = {
    2002: 'Бразилия',
    2006: 'Италия',
    2010: 'Испания',
    2014: 'Германия',
    2018: 'Франция',
}

#1.Добавляем в словарь ключ 2022 год и значение к нему "Аргентина".
world_champions[2022] = 'Аргентина'

#2.Чтобы вывести на экран и ключи, и значения используем метод items() и print().
for key, value in world_champions.items():
    print(key,' - ',value)

#3.Ищем среди ключей и значений с помощью конструкции if-in.
country = 'Италия'
if country in world_champions.keys() or country in world_champions.values():
    print('Италия cтановилась чемпионом мира по футболу в 21 веке!')
else:
    print('Италия не выигрывала чемпионат мира по футболу в 21 веке.')
